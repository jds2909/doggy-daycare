begin;

create table public.booking_enquiries (
  id uuid primary key default gen_random_uuid(),

  status text not null default 'NEW'
    check (status in ('NEW', 'PENDING_REVIEW', 'CONTACTED', 'CLOSED')),

  full_name text not null
    check (char_length(btrim(full_name)) between 2 and 120),
  email text not null
    check (char_length(btrim(email)) between 3 and 254),
  telephone text not null
    check (char_length(btrim(telephone)) between 7 and 30),
  home_address text not null
    check (char_length(btrim(home_address)) between 5 and 1000),
  postcode text not null
    check (char_length(btrim(postcode)) between 3 and 12),

  service text not null
    check (service in ('day-care', 'boarding')),
  day_care_dates_text text
    check ((
      day_care_dates_text is null
      or char_length(btrim(day_care_dates_text)) between 1 and 500
    ) is true),
  arrival_date date,
  departure_date date,
  preferred_arrival_time time without time zone,
  preferred_collection_time time without time zone,

  -- This records whether multiple submitted dogs will attend at the same time.
  -- It is not derived from the number of dog rows because the current form asks
  -- a scheduling question, not simply whether the household owns multiple dogs.
  multiple_dogs_same_household boolean not null,

  booking_notes text
    check ((
      booking_notes is null
      or char_length(booking_notes) <= 2000
    ) is true),

  -- These timestamps are generated by the database after the server has
  -- validated that both required confirmations were true.
  accuracy_confirmed_at timestamptz not null default now(),
  enquiry_acknowledged_at timestamptz not null default now(),

  form_version smallint not null default 1
    check (form_version > 0),

  -- Supplied as an idempotency token, not as a database record identifier.
  submission_key uuid not null unique,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint booking_enquiries_service_dates_check check ((
    (
      service = 'day-care'
      and nullif(btrim(day_care_dates_text), '') is not null
      and arrival_date is null
      and departure_date is null
    )
    or
    (
      service = 'boarding'
      and day_care_dates_text is null
      and arrival_date is not null
      and departure_date is not null
      and departure_date > arrival_date
    )
  ) is true)
);

create table public.enquiry_dogs (
  id uuid primary key default gen_random_uuid(),
  enquiry_id uuid not null
    references public.booking_enquiries (id)
    on delete cascade,

  position smallint not null
    check (position > 0),

  name text not null
    check (char_length(btrim(name)) between 1 and 100),
  breed text not null
    check (char_length(btrim(breed)) between 1 and 120),
  age_or_date_of_birth text not null
    check (char_length(btrim(age_or_date_of_birth)) between 1 and 100),
  sex text not null
    check (sex in ('female', 'male')),
  neutered boolean not null,

  microchipped boolean not null,
  microchip_number text
    check ((
      microchip_number is null
      or char_length(btrim(microchip_number)) between 1 and 100
    ) is true),

  insured boolean not null,
  insurance_company text
    check ((
      insurance_company is null
      or char_length(btrim(insurance_company)) between 1 and 200
    ) is true),
  insurance_policy_number text
    check ((
      insurance_policy_number is null
      or char_length(btrim(insurance_policy_number)) between 1 and 200
    ) is true),

  veterinary_practice_details text not null
    check (
      char_length(btrim(veterinary_practice_details)) between 1 and 1000
    ),
  vaccination_date date not null,
  worming_date date not null,
  flea_treatment_date date not null,

  has_medical_conditions boolean not null,
  medical_condition_details text
    check ((
      medical_condition_details is null
      or char_length(btrim(medical_condition_details)) between 1 and 2000
    ) is true),

  takes_prescribed_medication boolean not null,
  medication_details text
    check ((
      medication_details is null
      or char_length(btrim(medication_details)) between 1 and 2000
    ) is true),

  has_allergies boolean not null,
  allergy_details text
    check ((
      allergy_details is null
      or char_length(btrim(allergy_details)) between 1 and 2000
    ) is true),

  daily_routine text not null
    check (char_length(btrim(daily_routine)) between 1 and 3000),
  feeding_routine text not null
    check (char_length(btrim(feeding_routine)) between 1 and 2000),
  exercise_requirements text
    check ((
      exercise_requirements is null
      or char_length(btrim(exercise_requirements)) between 1 and 2000
    ) is true),
  sleeping_arrangements text
    check ((
      sleeping_arrangements is null
      or char_length(btrim(sleeping_arrangements)) between 1 and 2000
    ) is true),
  behaviour_with_other_dogs text not null
    check (
      char_length(btrim(behaviour_with_other_dogs)) between 1 and 2000
    ),
  separation_anxiety_details text
    check ((
      separation_anxiety_details is null
      or char_length(btrim(separation_anxiety_details)) between 1 and 2000
    ) is true),

  has_aggression_fear_or_reactivity boolean not null,
  aggression_fear_or_reactivity_details text
    check ((
      aggression_fear_or_reactivity_details is null
      or char_length(btrim(aggression_fear_or_reactivity_details))
        between 1 and 3000
    ) is true),

  other_care_information text
    check ((
      other_care_information is null
      or char_length(btrim(other_care_information)) between 1 and 3000
    ) is true),

  created_at timestamptz not null default now(),

  constraint enquiry_dogs_enquiry_position_unique
    unique (enquiry_id, position),

  constraint enquiry_dogs_microchip_check check ((
    (
      microchipped = true
      and nullif(btrim(microchip_number), '') is not null
    )
    or
    (
      microchipped = false
      and microchip_number is null
    )
  ) is true),

  constraint enquiry_dogs_insurance_check check ((
    (
      insured = true
      and nullif(btrim(insurance_company), '') is not null
      and nullif(btrim(insurance_policy_number), '') is not null
    )
    or
    (
      insured = false
      and insurance_company is null
      and insurance_policy_number is null
    )
  ) is true),

  constraint enquiry_dogs_medical_conditions_check check ((
    (
      has_medical_conditions = true
      and nullif(btrim(medical_condition_details), '') is not null
    )
    or
    (
      has_medical_conditions = false
      and medical_condition_details is null
    )
  ) is true),

  constraint enquiry_dogs_medication_check check ((
    (
      takes_prescribed_medication = true
      and nullif(btrim(medication_details), '') is not null
    )
    or
    (
      takes_prescribed_medication = false
      and medication_details is null
    )
  ) is true),

  constraint enquiry_dogs_allergies_check check ((
    (
      has_allergies = true
      and nullif(btrim(allergy_details), '') is not null
    )
    or
    (
      has_allergies = false
      and allergy_details is null
    )
  ) is true),

  constraint enquiry_dogs_behaviour_history_check check ((
    (
      has_aggression_fear_or_reactivity = true
      and nullif(
        btrim(aggression_fear_or_reactivity_details),
        ''
      ) is not null
    )
    or
    (
      has_aggression_fear_or_reactivity = false
      and aggression_fear_or_reactivity_details is null
    )
  ) is true)
);

create table public.dog_permissions (
  dog_id uuid primary key
    references public.enquiry_dogs (id)
    on delete cascade,

  feeding_with_other_dogs boolean not null,
  on_lead_walking boolean not null,
  off_lead_walking boolean not null,
  walking_with_other_households boolean not null,
  socialising_with_other_households boolean not null,
  overnight_with_other_households boolean not null,

  crate_required boolean not null,
  crate_provision_agreed boolean,

  medication_administration boolean not null,
  emergency_treatment_acknowledged boolean not null,

  recorded_at timestamptz not null default now(),

  constraint dog_permissions_crate_check check ((
    (
      crate_required = true
      and crate_provision_agreed = true
    )
    or
    (
      crate_required = false
      and crate_provision_agreed is null
    )
  ) is true)
);

create index booking_enquiries_status_created_at_idx
  on public.booking_enquiries (status, created_at desc);

comment on table public.booking_enquiries is
  'Historical snapshots of unconfirmed booking enquiries.';
comment on table public.enquiry_dogs is
  'Dogs included in a booking enquiry; not permanent customer dog profiles.';
comment on table public.dog_permissions is
  'Per-dog permissions and acknowledgements captured with an enquiry.';

alter table public.booking_enquiries enable row level security;
alter table public.enquiry_dogs enable row level security;
alter table public.dog_permissions enable row level security;

-- No RLS policies are created for public browser roles. The future Route
-- Handler will use a server-only Supabase secret and perform all validation.
revoke all privileges on table public.booking_enquiries
  from public, anon, authenticated;
revoke all privileges on table public.enquiry_dogs
  from public, anon, authenticated;
revoke all privileges on table public.dog_permissions
  from public, anon, authenticated;

grant select, insert, update, delete on table public.booking_enquiries
  to service_role;
grant select, insert, update, delete on table public.enquiry_dogs
  to service_role;
grant select, insert, update, delete on table public.dog_permissions
  to service_role;

commit;
